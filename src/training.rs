//! Pure-Rust AlphaZero Replay Buffer, Combined Policy-Value Loss, and `AdamW` Training Loop
//! (port & evolution of `train/main.py` and `train/utils.py` without Python or C-FFI).

use std::path::Path;

use candle_core::{DType, Device, Result, Tensor};
use candle_nn::{AdamW, Optimizer, ParamsAdamW, VarBuilder, VarMap, ops::log_softmax};
use rand::prelude::RngExt;

use crate::alphazero::TrainingPosition;
use crate::inference::InferenceService;
use crate::nn::{AlphaZeroNet, AlphaZeroNetConfig, CandleBatchEvaluator};

/// Circular experience replay buffer storing [`TrainingPosition<G, P, N>`] examples
/// generated by Game-Parallel AlphaZero Self-Play (replaces `ReplayBuffer` in `train/utils.py`).
#[derive(Clone, Debug)]
pub struct ReplayBuffer<const G: usize, const P: usize, const N: usize> {
    buffer: Vec<TrainingPosition<G, P, N>>,
    capacity: usize,
    write_pos: usize,
}

impl<const G: usize, const P: usize, const N: usize> ReplayBuffer<G, P, N> {
    pub fn new(capacity: usize) -> Self {
        assert!(capacity > 0, "ReplayBuffer capacity must be > 0");
        Self {
            buffer: Vec::with_capacity(capacity.min(65_536)),
            capacity,
            write_pos: 0,
        }
    }

    #[inline]
    pub fn len(&self) -> usize {
        self.buffer.len()
    }

    #[inline]
    pub fn is_empty(&self) -> bool {
        self.buffer.is_empty()
    }

    #[inline]
    pub const fn capacity(&self) -> usize {
        self.capacity
    }

    /// Inserts a single [`TrainingPosition`], overwriting the oldest entry once `capacity` is reached.
    pub fn push(&mut self, pos: TrainingPosition<G, P, N>) {
        if self.buffer.len() < self.capacity {
            self.buffer.push(pos);
        } else {
            self.buffer[self.write_pos] = pos;
        }
        self.write_pos = (self.write_pos + 1) % self.capacity;
    }

    /// Appends a slice of self-play positions into the ring buffer.
    pub fn extend(&mut self, positions: &[TrainingPosition<G, P, N>]) {
        for pos in positions {
            self.push(pos.clone());
        }
    }

    /// Uniformly samples `batch_size` positions into contiguous flat buffers
    /// `(states [B * G], policies [B * P], values [B * N])`.
    pub fn sample_flat_batch(
        &self,
        batch_size: usize,
        states_out: &mut Vec<f32>,
        policies_out: &mut Vec<f32>,
        values_out: &mut Vec<f32>,
        rng: &mut impl RngExt,
    ) {
        assert!(
            !self.buffer.is_empty(),
            "cannot sample from an empty ReplayBuffer"
        );
        states_out.clear();
        policies_out.clear();
        values_out.clear();
        states_out.reserve(batch_size * G);
        policies_out.reserve(batch_size * P);
        values_out.reserve(batch_size * N);

        let len = self.buffer.len();
        for _ in 0..batch_size {
            let idx = rng.random_range(0..len);
            let item = &self.buffer[idx];
            states_out.extend_from_slice(&item.state);
            policies_out.extend_from_slice(&item.policy);
            values_out.extend_from_slice(&item.value);
        }
    }
}

/// Loss breakdown from a single mini-batch gradient step or training epoch.
#[derive(Clone, Copy, Debug, Default)]
pub struct TrainMetrics {
    pub total_loss: f32,
    pub policy_loss: f32,
    pub value_loss: f32,
}

/// Pure-Rust AlphaZero trainer owning the master [`VarMap`], [`AlphaZeroNet`], and [`AdamW`] optimizer.
pub struct AlphaZeroTrainer<const G: usize, const P: usize, const N: usize> {
    varmap: VarMap,
    net: AlphaZeroNet<G, P, N>,
    optimizer: AdamW,
    device: Device,
    net_config: AlphaZeroNetConfig,
    states_scratch: Vec<f32>,
    policies_scratch: Vec<f32>,
    values_scratch: Vec<f32>,
}

impl<const G: usize, const P: usize, const N: usize> AlphaZeroTrainer<G, P, N> {
    /// Creates a new [`AlphaZeroTrainer`] on `device` with learning rate `lr` and weight decay `weight_decay`.
    pub fn new(
        net_config: AlphaZeroNetConfig,
        lr: f64,
        weight_decay: f64,
        device: Device,
    ) -> Result<Self> {
        let varmap = VarMap::new();
        let vb = VarBuilder::from_varmap(&varmap, DType::F32, &device);
        let net = AlphaZeroNet::new(vb, &net_config)?;
        let params = ParamsAdamW {
            lr,
            weight_decay,
            ..Default::default()
        };
        let optimizer = AdamW::new(varmap.all_vars(), params)?;

        Ok(Self {
            varmap,
            net,
            optimizer,
            device,
            net_config,
            states_scratch: Vec::new(),
            policies_scratch: Vec::new(),
            values_scratch: Vec::new(),
        })
    }

    #[inline]
    pub const fn device(&self) -> &Device {
        &self.device
    }

    #[inline]
    pub const fn net(&self) -> &AlphaZeroNet<G, P, N> {
        &self.net
    }

    #[inline]
    pub const fn varmap(&self) -> &VarMap {
        &self.varmap
    }

    #[inline]
    pub fn set_learning_rate(&mut self, lr: f64) {
        self.optimizer.set_learning_rate(lr);
    }

    /// Builds a lock-free batched [`InferenceService`] sharing this trainer's live model weights.
    ///
    /// - On a single device (`devices.len() == 1`), Worker `0` shares `self.varmap` in-place with
    ///   zero weight-copy overhead.
    /// - On multi-GPU RunPod deployments (`devices.len() > 1`), spawns one inference worker thread
    ///   per GPU device and synchronizes weights via [`CandleBatchEvaluator::sync_workers`].
    pub fn build_inference_service(
        &self,
        max_batch_size: usize,
        devices: &[Device],
    ) -> Result<InferenceService<CandleBatchEvaluator<G, P, N>, G, P, N>> {
        let evaluator =
            CandleBatchEvaluator::new(&self.varmap, &self.net, &self.net_config, devices)?;
        let num_workers = evaluator.num_replicas();
        Ok(InferenceService::new(evaluator, max_batch_size, num_workers))
    }

    /// Executes a single mini-batch forward + backward + `AdamW` step on flat batch slices
    /// (`states_flat` of len `B * G`, `policies_flat` of len `B * P`, `values_flat` of len `B * N`).
    pub fn train_step_flat(
        &mut self,
        states_flat: &[f32],
        policies_flat: &[f32],
        values_flat: &[f32],
        batch_size: usize,
    ) -> Result<TrainMetrics> {
        let states = Tensor::from_slice(states_flat, (batch_size, G), &self.device)?;
        let target_policies = Tensor::from_slice(policies_flat, (batch_size, P), &self.device)?;
        let target_values = Tensor::from_slice(values_flat, (batch_size, N), &self.device)?;

        let (pred_logits, pred_values) = self.net.forward(&states)?;

        // Policy cross-entropy loss: `- (1 / B) * sum(pi * log_softmax(logits))`
        let log_probs = log_softmax(&pred_logits, 1)?;
        let policy_loss = (&target_policies * &log_probs)?
            .sum_all()?
            .affine(-1.0 / (batch_size as f64), 0.0)?;

        // Value MSE loss: `mean((v_pred - v_target)^2)`
        let value_loss = (&pred_values - &target_values)?.sqr()?.mean_all()?;
        let total_loss = (&policy_loss + &value_loss)?;

        self.optimizer.backward_step(&total_loss)?;

        Ok(TrainMetrics {
            total_loss: total_loss.to_scalar::<f32>()?,
            policy_loss: policy_loss.to_scalar::<f32>()?,
            value_loss: value_loss.to_scalar::<f32>()?,
        })
    }

    /// Runs `steps` mini-batch gradient updates sampled uniformly from `buffer`, pausing
    /// `service` during the weight update and synchronizing multi-GPU replicas before resuming.
    pub fn train_epoch(
        &mut self,
        buffer: &ReplayBuffer<G, P, N>,
        service: &InferenceService<CandleBatchEvaluator<G, P, N>, G, P, N>,
        batch_size: usize,
        steps: usize,
        rng: &mut impl RngExt,
    ) -> Result<TrainMetrics> {
        assert!(steps > 0, "steps must be > 0");
        service.pause_inference();

        let mut sum_total = 0.0f32;
        let mut sum_policy = 0.0f32;
        let mut sum_value = 0.0f32;

        for _ in 0..steps {
            let mut st = std::mem::take(&mut self.states_scratch);
            let mut pol = std::mem::take(&mut self.policies_scratch);
            let mut val = std::mem::take(&mut self.values_scratch);

            buffer.sample_flat_batch(batch_size, &mut st, &mut pol, &mut val, rng);
            let res = self.train_step_flat(&st, &pol, &val, batch_size);

            self.states_scratch = st;
            self.policies_scratch = pol;
            self.values_scratch = val;

            let metrics = res?;
            sum_total += metrics.total_loss;
            sum_policy += metrics.policy_loss;
            sum_value += metrics.value_loss;
        }

        service.evaluator().sync_workers()?;
        service.resume_inference();

        let inv = 1.0 / (steps as f32);
        Ok(TrainMetrics {
            total_loss: sum_total * inv,
            policy_loss: sum_policy * inv,
            value_loss: sum_value * inv,
        })
    }

    /// Saves the model weights to `path` in `.safetensors` format.
    pub fn save_checkpoint<Pth: AsRef<Path>>(&self, path: Pth) -> Result<()> {
        self.varmap.save(path)
    }

    /// Loads model weights from a `.safetensors` checkpoint at `path`.
    pub fn load_checkpoint<Pth: AsRef<Path>>(&mut self, path: Pth) -> Result<()> {
        self.varmap.load(path)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use rand::prelude::{SeedableRng, SmallRng};

    use crate::alphazero::{AlphaZeroConfig, AlphaZeroPlayer, SelfPlayConfig, run_self_play};
    use crate::game::PlayerIndex;
    use crate::games::tic_tac_toe::{EMPTY_STATE, TicTacToe, TttGame};
    use crate::matchup::{RandomPlayer, run_multi_match};
    use crate::player::Player;

    #[test]
    fn resnet2d_and_resmlp_forward_and_safetensors_roundtrip() {
        let dev = Device::Cpu;
        let mut trainer_cnn = AlphaZeroTrainer::<27, 9, 2>::new(
            AlphaZeroNetConfig::tic_tac_toe_resnet(),
            1e-3,
            1e-4,
            dev.clone(),
        )
        .expect("failed to build ResNet2d trainer");

        use crate::inference::BatchEvaluator;

        let service = trainer_cnn
            .build_inference_service(16, &[dev.clone(), dev.clone(), dev.clone(), dev])
            .expect("failed to build multi-worker InferenceService");
        assert_eq!(service.num_workers(), 4);

        let client = service.client(4);
        let test_state = [0.5f32; 27];
        client.submit(0, test_state);
        client.notify_service();
        client.wait_for_response();
        let resp1 = client.try_pop().expect("expected response");
        assert!(resp1.value[0] >= -1.0 && resp1.value[0] <= 1.0);
        assert!(resp1.value[1] >= -1.0 && resp1.value[1] <= 1.0);

        // Save to a temporary `.safetensors` file, perturb weights via a training step,
        // synchronize all 4 worker replicas in parallel, and verify all 4 replicas match!
        let tmp_path = std::env::temp_dir().join("mcts_test_ttt_checkpoint.safetensors");
        trainer_cnn
            .save_checkpoint(&tmp_path)
            .expect("failed to save safetensors");

        let mut target_pol = [0.0f32; 9];
        target_pol[4] = 1.0;
        trainer_cnn
            .train_step_flat(&test_state, &target_pol, &[1.0, -1.0], 1)
            .expect("train step failed");
        service
            .evaluator()
            .sync_workers()
            .expect("parallel sync_workers failed");

        let mut p0 = [[0.0f32; 9]; 1];
        let mut v0 = [[0.0f32; 2]; 1];
        service
            .evaluator()
            .evaluate_batch(0, &[test_state], &mut p0, &mut v0);
        for w in 1..4 {
            let mut pw = [[0.0f32; 9]; 1];
            let mut vw = [[0.0f32; 2]; 1];
            service
                .evaluator()
                .evaluate_batch(w, &[test_state], &mut pw, &mut vw);
            assert_eq!(p0, pw, "replica {w} policy logits out of sync with master");
            assert_eq!(v0, vw, "replica {w} values out of sync with master");
        }

        trainer_cnn
            .load_checkpoint(&tmp_path)
            .expect("failed to reload safetensors");
        service
            .evaluator()
            .sync_workers()
            .expect("parallel sync_workers after reload failed");
        let _ = std::fs::remove_file(&tmp_path);

        client.submit(0, test_state);
        client.notify_service();
        client.wait_for_response();
        let resp2 = client.try_pop().expect("expected response after reload");
        for (a, b) in resp1.policy_logits.iter().zip(resp2.policy_logits.iter()) {
            assert!((a - b).abs() < 1e-6, "expected restored logits to match: {a} vs {b}");
        }
        for (a, b) in resp1.value.iter().zip(resp2.value.iter()) {
            assert!((a - b).abs() < 1e-6, "expected restored values to match: {a} vs {b}");
        }
    }

    #[test]
    fn pure_rust_alphazero_training_loop_reduces_loss_and_learns_tic_tac_toe() {
        let dev = Device::Cpu;
        let mut trainer = AlphaZeroTrainer::<27, 9, 2>::new(
            AlphaZeroNetConfig::tic_tac_toe_mlp(),
            3e-3,
            1e-4,
            dev.clone(),
        )
        .expect("failed to initialize trainer");

        let service = trainer
            .build_inference_service(32, &[dev])
            .expect("failed to start InferenceService");

        let root_game = TttGame::new(PlayerIndex::PLAYER1, EMPTY_STATE);
        let sp_cfg = SelfPlayConfig::new(16, 24, 2026)
            .with_workers(2)
            .with_opening_moves(2);

        let mut buffer = ReplayBuffer::<27, 9, 2>::new(4096);
        let sp_res = run_self_play(&root_game, &service, &sp_cfg);
        buffer.extend(&sp_res.positions);
        assert!(buffer.len() >= 80);

        let mut rng = SmallRng::seed_from_u64(42);
        let first_metrics = trainer
            .train_epoch(&buffer, &service, 32, 4, &mut rng)
            .expect("epoch 1 failed");
        let mut last_metrics = first_metrics;
        for _ in 0..6 {
            last_metrics = trainer
                .train_epoch(&buffer, &service, 32, 8, &mut rng)
                .expect("training epoch failed");
        }

        assert!(
            last_metrics.total_loss < first_metrics.total_loss,
            "expected total loss to decrease across training epochs: first={first_metrics:?}, last={last_metrics:?}"
        );

        // Evaluate the trained AlphaZero network in a batched MultiMatch against RandomPlayer!
        let f_az = |g: &TttGame, seed: u64| -> Box<dyn Player<TicTacToe, 2> + '_> {
            Box::new(AlphaZeroPlayer::new(
                *g,
                &service,
                AlphaZeroConfig::new(1, 32, seed).with_dirichlet(0.3, 0.0),
            ))
        };
        let f_rnd = |g: &TttGame, seed: u64| -> Box<dyn Player<TicTacToe, 2> + '_> {
            Box::new(RandomPlayer::new(*g, seed))
        };
        let eval_summary = run_multi_match(&root_game, [&f_az, &f_rnd], 20, 2, 777);
        assert!(
            eval_summary.wins[0] + eval_summary.draws >= 16,
            "expected trained AlphaZeroPlayer to dominate RandomPlayer, got {eval_summary:?}"
        );
    }
}
